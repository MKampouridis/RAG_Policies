"""Generate eval/questions_milestones.json: one PROGRAMME-level question per
current milestone document, with its code list as the completeness gold."""
import json, re, sys, collections
sys.path.insert(0, ".")
from src.ingest import _get_collection

CODE = re.compile(r"\b[MC]\d+\.\d+")
PAT = re.compile(r"Entry\s+(.*?)\s+Students\s+Postgraduate Research milestones", re.I)
# The three Essex faculties, named explicitly. A general "Faculty of <words>"
# pattern is greedy over letters and swallows the PROGRAMME that follows it -
# it parsed only the 8 programmes whose names contain a digit or hyphen
# ("3-Paper PhD") and silently dropped the other 72.
FACULTY = re.compile(r"\s*Faculty of (?:Social Sciences|Science and Health|Arts and Humanities)\s*")

c = _get_collection(); d = c.get(include=["metadatas", "documents"])
text = collections.defaultdict(dict); cur = {}
for m, doc in zip(d["metadatas"], d["documents"]):
    u = m.get("source_url", "")
    if "/pgre/milestones-2025-26/" not in u or not m.get("is_current"): continue
    text[u][m.get("chunk_index") or 0] = doc
    cur[u] = True

items, skipped = [], []
for u, chunks in sorted(text.items()):
    body = " ".join(chunks[k] for k in sorted(chunks))
    head = chunks.get(0, "")[:260].replace("\n", " ")
    m = PAT.search(head)
    if not m:
        skipped.append(u.rsplit("/", 1)[-1]); continue
    label = m.group(1).strip()
    parts = FACULTY.split(label)
    dept = parts[0].strip().lstrip("The ").strip()
    prog = parts[-1].strip() if len(parts) > 1 else ""
    if not prog:
        skipped.append(u.rsplit("/", 1)[-1]); continue
    codes = sorted(set(CODE.findall(body)))
    if not codes:
        skipped.append(u.rsplit("/", 1)[-1]); continue
    items.append({
        "source_url": u,
        "source_title": u.rsplit("/", 1)[-1],
        "doc_type": "rules_of_assessment",
        "department": dept,
        "programme": prog,
        # PROGRAMME-level, not department-level. Departments publish up to five
        # near-identical milestone documents (Essex Business School: standard,
        # 3-Paper, Integrated, and Sustainable Transitions variants of both), so
        # a department-only question is genuinely ambiguous and cannot have one
        # gold document. Asking the way a student or supervisor actually asks -
        # naming the programme - is what makes this set scoreable at all.
        "question": (f"What are the milestones for "
                     f"{'an' if prog[:1].upper() in 'AEIOU' else 'a'} {prog} "
                     f"student in {dept}?"),
        "milestone_codes": codes,
        "n_codes": len(codes),
    })

out = {
    "_note": ("Milestone completeness probe. Generated by "
              "eval/build_milestone_questions.py from the corpus itself, so it "
              "regenerates after an ingest rather than going stale. Score by "
              "whether the answer covers every code in milestone_codes - by "
              "DESCRIPTION, not by the code label: answers legitimately "
              "enumerate in prose without printing 'M1.1', and a label-only "
              "metric scored five such answers 0/N when they were complete."),
    "items": items,
}
json.dump(out, open("eval/questions_milestones.json", "w"), indent=1, ensure_ascii=False)
print(f"  wrote {len(items)} programme-level questions; skipped {len(skipped)}")
for s in skipped: print("    skipped:", s)
tot = sum(i["n_codes"] for i in items)
print(f"  codes covered: {tot}   departments: {len({i['department'] for i in items})}")
